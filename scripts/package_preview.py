"""Package tracked runtime files without credentials or local file permissions."""

import argparse
from datetime import datetime, timezone
import io
import json
from pathlib import Path
import subprocess
import tarfile

ROOT = Path(__file__).resolve().parents[1]
RUNTIME_ROOTS = {"scripts", "public", "data", "minigames"}
RUNTIME_FILES = {"config.yml", "requirements.txt"}


def runtime_path(path):
    return path.name != ".DS_Store" and (path.parts[0] in RUNTIME_ROOTS or path.as_posix() in RUNTIME_FILES
            or path.parent == Path("infra/nginx") and path.suffix == ".conf"
            or len(path.parts) == 1 and path.suffix in {".mjs", ".js", ".html", ".css", ".svg"})


def package(output, root=ROOT):
    untracked = subprocess.run(["git", "-C", str(root), "ls-files", "--others", "--exclude-standard", "-z"],
                               capture_output=True, check=True).stdout.decode().split("\0")
    source_suffixes = {".mjs", ".js", ".py", ".html", ".css", ".svg", ".conf"}
    missing = [name for name in untracked if name and runtime_path(Path(name))
               and (Path(name).suffix in source_suffixes or name in RUNTIME_FILES)]
    if missing:
        raise ValueError("Untracked runtime source files would be omitted; review and commit required files "
                         "before packaging: " + ", ".join(sorted(missing)[:12]))
    files = subprocess.run(["git", "-C", str(root), "ls-files", "-z"],
                           capture_output=True, check=True).stdout.decode().split("\0")
    runtime = [name for name in files if name and runtime_path(Path(name))]
    commit = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                            capture_output=True, check=True, text=True).stdout.strip()
    clean = subprocess.run(["git", "-C", str(root), "diff", "--quiet", "HEAD", "--", *runtime],
                           check=False)
    if clean.returncode == 1:
        raise ValueError("Commit runtime changes before packaging a deployment checkpoint.")
    clean.check_returncode()
    with tarfile.open(output, "w:gz", format=tarfile.PAX_FORMAT) as archive:
        for name in runtime:
            if name == "public/release.json":
                raise ValueError("public/release.json is generated by the deployment packager, not tracked.")
            path = root / name
            if path.is_symlink() or not path.is_file():
                raise ValueError("Runtime package requires regular tracked files.")
            info = archive.gettarinfo(str(path), arcname=name)
            info.mode = 0o644
            info.uid = info.gid = 0
            info.uname = info.gname = "root"
            info.pax_headers = {}
            with path.open("rb") as source:
                archive.addfile(info, source)
        release = json.dumps({"version": 1, "commit": commit,
                              "packagedAt": datetime.now(timezone.utc).isoformat()}).encode()
        info = tarfile.TarInfo("public/release.json")
        info.mode = 0o644
        info.size = len(release)
        archive.addfile(info, io.BytesIO(release))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    package(args.output)
