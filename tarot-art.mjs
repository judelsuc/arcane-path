  empress: ["   vvv   ", "    @    ", "  (/|\\)  ", "  [_*_]  "],
  emperor: ["   WWW   ", "    @  + ", "  [/|\\]| ", "  [___]| "],
  hierophant: ["    +    ", "   _+_   ", "    @    ", "  o/|\\o  "],
  lovers: ["    <3   ", "  @    @ ", " /|\\--/|\\", " / \\  / \\"],
  chariot: ["  \\ @ /  ", "  [=|=]  ", "  |___|  ", "  O   O  "],
  justice: ["    @    ", " +--|--+ ", "(_) | (_)", "   / \\   "],
  hermit: ["  *      ", " [*] @   ", "   |/|\\  ", "   |/ \\  "],
